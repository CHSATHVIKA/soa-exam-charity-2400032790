import { useState } from 'react'
import { useNavigate, Link } from 'react-router-dom'
import { useCharity } from '../context/CharityContext'

export default function AddRecord() {
  const navigate = useNavigate()
  const { addCharity } = useCharity()

  const [form, setForm] = useState({
    fundraiserName: '',
    targetAmount: '',
    amountRaised: '',
    completed: false,
  })

  const [errors, setErrors] = useState({})
  const [submitting, setSubmitting] = useState(false)

  const validate = () => {
    const errs = {}
    if (!form.fundraiserName.trim()) {
      errs.fundraiserName = 'Fundraiser name is required.'
    } else if (form.fundraiserName.trim().length < 3) {
      errs.fundraiserName = 'Name must be at least 3 characters.'
    } else if (form.fundraiserName.trim().length > 100) {
      errs.fundraiserName = 'Name cannot exceed 100 characters.'
    }

    if (form.targetAmount === '' || form.targetAmount === null) {
      errs.targetAmount = 'Target goal is required.'
    } else if (Number(form.targetAmount) <= 0) {
      errs.targetAmount = 'Target goal must be a positive number greater than 0.'
    }

    if (form.amountRaised === '' || form.amountRaised === null) {
      errs.amountRaised = 'Amount raised is required.'
    } else if (Number(form.amountRaised) < 0) {
      errs.amountRaised = 'Amount raised cannot be negative.'
    }

    return errs
  }

  const handleChange = (e) => {
    const { name, value, type, checked } = e.target
    const val = type === 'checkbox' ? checked : value
    setForm((prev) => ({ ...prev, [name]: val }))

    if (errors[name]) {
      setErrors((prev) => ({ ...prev, [name]: '' }))
    }
  }

  const handleSubmit = async (e) => {
    e.preventDefault()
    const validationErrors = validate()
    if (Object.keys(validationErrors).length > 0) {
      setErrors(validationErrors)
      return
    }

    setSubmitting(true)
    try {
      const payload = {
        fundraiserName: form.fundraiserName.trim(),
        targetAmount: Number(form.targetAmount),
        amountRaised: Number(form.amountRaised),
        completed: Boolean(form.completed),
      }
      await addCharity(payload)
      navigate('/records')
    } catch {
      // Error handled by context toast
    } finally {
      setSubmitting(false)
    }
  }

  return (
    <div className="py-4">
      <div className="row justify-content-center">
        <div className="col-12 col-lg-8">
          {/* Header */}
          <div className="d-flex justify-content-between align-items-center mb-4">
            <div>
              <h4 className="fw-bold text-dark mb-1">Add New Fundraiser</h4>
              <p className="text-muted small mb-0">
                Register a new charity campaign. Data will be persisted in PostgreSQL table <code>exam_2400032790</code>.
              </p>
            </div>
            <Link to="/records" className="btn btn-outline-secondary btn-sm rounded-pill px-3">
              ← Back to Directory
            </Link>
          </div>

          {/* Database Notice */}
          <div className="alert alert-light border d-flex align-items-center gap-3 p-3 rounded-3 mb-4 shadow-sm">
            <div className="bg-primary text-white p-2 rounded-circle d-flex align-items-center justify-content-center" style={{ width: '32px', height: '32px' }}>
              <i className="bi bi-info-lg"></i>
            </div>
            <div className="small text-secondary">
              <strong>Database Auto-ID Rule:</strong> This form does not contain an ID field. The unique fundraiser ID is automatically generated by the backend and database sequence upon creation.
            </div>
          </div>

          {/* Form Card with Floating Labels */}
          <div className="card card-saas p-4">
            <form onSubmit={handleSubmit} noValidate>
              <div className="row g-3">
                {/* Fundraiser Name */}
                <div className="col-12">
                  <div className="form-floating">
                    <input
                      type="text"
                      className={`form-control ${errors.fundraiserName ? 'is-invalid' : form.fundraiserName ? 'is-valid' : ''}`}
                      id="floatingName"
                      placeholder="Fundraiser Name"
                      name="fundraiserName"
                      value={form.fundraiserName}
                      onChange={handleChange}
                      maxLength={100}
                      required
                    />
                    <label htmlFor="floatingName">Fundraiser Campaign Name *</label>
                    {errors.fundraiserName && (
                      <div className="invalid-feedback">{errors.fundraiserName}</div>
                    )}
                  </div>
                  <div className="form-text small">Descriptive title between 3 and 100 characters.</div>
                </div>

                {/* Target Amount */}
                <div className="col-12 col-md-6">
                  <div className="form-floating">
                    <input
                      type="number"
                      className={`form-control ${errors.targetAmount ? 'is-invalid' : form.targetAmount ? 'is-valid' : ''}`}
                      id="floatingTarget"
                      placeholder="50000"
                      name="targetAmount"
                      min="1"
                      step="0.01"
                      value={form.targetAmount}
                      onChange={handleChange}
                      required
                    />
                    <label htmlFor="floatingTarget">Target Budget Goal (₹) *</label>
                    {errors.targetAmount && (
                      <div className="invalid-feedback">{errors.targetAmount}</div>
                    )}
                  </div>
                  <div className="form-text small">Total fund goal required for the project.</div>
                </div>

                {/* Amount Raised */}
                <div className="col-12 col-md-6">
                  <div className="form-floating">
                    <input
                      type="number"
                      className={`form-control ${errors.amountRaised ? 'is-invalid' : form.amountRaised ? 'is-valid' : ''}`}
                      id="floatingRaised"
                      placeholder="10000"
                      name="amountRaised"
                      min="0"
                      step="0.01"
                      value={form.amountRaised}
                      onChange={handleChange}
                      required
                    />
                    <label htmlFor="floatingRaised">Current Amount Collected (₹) *</label>
                    {errors.amountRaised && (
                      <div className="invalid-feedback">{errors.amountRaised}</div>
                    )}
                  </div>
                  <div className="form-text small">Initial or current amount raised (&ge; 0).</div>
                </div>

                {/* Completed Toggle */}
                <div className="col-12">
                  <div className="p-3 bg-light rounded-3 border">
                    <div className="form-check form-switch mb-0">
                      <input
                        className="form-check-input"
                        type="checkbox"
                        role="switch"
                        id="completedSwitch"
                        name="completed"
                        checked={form.completed}
                        onChange={handleChange}
                      />
                      <label className="form-check-label fw-semibold text-dark ms-2" htmlFor="completedSwitch">
                        Campaign Status: Goal Achieved / Completed
                      </label>
                    </div>
                    <small className="text-muted d-block ps-4 mt-1">
                      Toggle this to indicate that the fundraiser has reached its goal or has concluded.
                    </small>
                  </div>
                </div>

                {/* Buttons */}
                <div className="col-12 d-flex gap-2 pt-3 border-top mt-4">
                  <button
                    type="submit"
                    className="btn btn-primary px-4 py-2 rounded-pill fw-semibold d-inline-flex align-items-center gap-2 shadow-sm"
                    disabled={submitting}
                  >
                    {submitting ? (
                      <>
                        <span className="spinner-border spinner-border-sm" role="status"></span>
                        <span>Saving Record...</span>
                      </>
                    ) : (
                      <>
                        <i className="bi bi-check-lg"></i>
                        <span>Save Fundraiser Record</span>
                      </>
                    )}
                  </button>
                  <button
                    type="button"
                    className="btn btn-light border px-4 py-2 rounded-pill"
                    onClick={() => navigate('/records')}
                    disabled={submitting}
                  >
                    Cancel
                  </button>
                </div>
              </div>
            </form>
          </div>
        </div>
      </div>
    </div>
  )
}
